"""CUPS backend tests: fake USB, real Ghostscript/CUPS rendering when installed."""

import asyncio
import io
from pathlib import Path
import shutil
import subprocess
from unittest.mock import AsyncMock, patch

import pytest
import usb.core

needs_gs = pytest.mark.skipif(not shutil.which("gs"), reason="Ghostscript not installed")
CUPSFILTER = shutil.which("cupsfilter") or shutil.which("cupsfilter", path="/usr/sbin")

LABEL_PS = b"""%!PS
<< /PageSize [39.685039 85.039370] >> setpagedevice
0 setgray 8.5 4 2 20 rectfill
/Helvetica findfont 9 scalefont setfont 14 40 moveto (QR) show
showpage
"""


def make_pdf(path: Path, pages: int = 1) -> Path:
    source = path.with_suffix(".ps")
    source.write_bytes(LABEL_PS + b"0 setgray 10 10 20 20 rectfill showpage\n" * (pages - 1))
    subprocess.run(["gs", "-q", "-dSAFER", "-dBATCH", "-dNOPAUSE", "-sDEVICE=pdfwrite",
                    f"-sOutputFile={path}", str(source)], check=True)
    return path


def pgm(pixels: bytes) -> bytes:
    return b"P5\n# Image generated by GPL Ghostscript\n112 240\n255\n" + pixels


def run(backend, *args, uri="fichero://usb?serial=EXAMPLE123", monkeypatch=None):
    monkeypatch.setenv("DEVICE_URI", uri)
    return backend.main(["fichero", "1", "user", "title", *args])


# --- Parsing -------------------------------------------------------------------


@pytest.mark.parametrize("uri", [
    "usb:///D11s", "fichero://usb", "fichero://usb?serial=x&serial=y",
    "fichero://usb?serial=x&file=/etc/passwd", "fichero://usb?serial=../x",
    "fichero://usb/path?serial=x", "fichero://usb?serial=%C3%A9",
])
def test_reject_invalid_uri(backend, uri):
    with pytest.raises(ValueError):
        backend.parse_uri(uri)


def test_serial_and_density(backend):
    assert backend.parse_uri("fichero://usb?serial=EXAMPLE123") == "EXAMPLE123"
    assert backend.parse_options("PageSize=14x30mm FicheroDensity=1") == (1, 4, -8)
    assert backend.parse_options("") == (2, 4, -8)  # Calibrated defaults, as in the PPD.
    assert backend.parse_options("FicheroShiftUp=0 FicheroShiftRight=0") == (2, 0, 0)
    assert backend.parse_options("FicheroShiftUp=-3 FicheroShiftRight=16") == (2, -3, 16)
    for bad in ("FicheroDensity=3", "FicheroShiftUp=17", "FicheroShiftRight=-17"):
        with pytest.raises(ValueError):
            backend.parse_options(bad)


def test_read_pdf_rejects_non_pdf_and_oversize(backend, monkeypatch):
    with pytest.raises(ValueError, match="Expected a PDF"):
        backend.read_pdf(io.BytesIO(b"not a pdf"))
    monkeypatch.setattr(backend, "MAX_JOB_BYTES", 8)
    with pytest.raises(ValueError, match="32 MiB"):
        backend.read_pdf(io.BytesIO(b"%PDF-1.4 and more"))


# --- Raster --------------------------------------------------------------------


def test_raster_threshold_crop_and_bit_order(backend, tmp_path):
    pixels = bytearray([255] * 112 * 240)
    pixels[100 * 112 + 7] = 0  # Left margin: cropped.
    pixels[100 * 112 + 8] = 0  # First printhead dot -> MSB of byte 0.
    pixels[100 * 112 + 103] = 127  # Last printhead dot, dark enough -> LSB.
    pixels[100 * 112 + 50] = 128  # Light gray -> white.
    path = tmp_path / "page.pgm"
    path.write_bytes(pgm(bytes(pixels)))
    raster = backend.pgm_to_raster(path)
    assert len(raster) == 12 * 240
    row = raster[100 * 12:101 * 12]
    assert row == bytes([0x80]) + bytes(10) + bytes([0x01])
    assert raster.count(0) == len(raster) - 2


def black_dots(raster):
    return {(y, x) for y in range(240) for x in range(96)
            if raster[y * 12 + x // 8] >> (7 - x % 8) & 1}


def test_raster_shift_moves_design_up_and_right(backend, tmp_path):
    pixels = bytearray([255] * 112 * 240)
    pixels[100 * 112 + 50] = 0  # Head dot 42, row 100.
    path = tmp_path / "page.pgm"
    path.write_bytes(pgm(bytes(pixels)))
    assert black_dots(backend.pgm_to_raster(path)) == {(100, 42)}
    # Landscape: up = towards head dot 95, right = towards the last row.
    assert black_dots(backend.pgm_to_raster(path, up=3, right=5)) == {(105, 45)}
    assert black_dots(backend.pgm_to_raster(path, up=-16, right=-16)) == {(84, 26)}
    # Content shifted past an edge is dropped, the margin brings white in.
    pixels[0 * 112 + 8] = 0
    path.write_bytes(pgm(bytes(pixels)))
    assert (0, 0) not in black_dots(backend.pgm_to_raster(path, up=1, right=1))
    assert black_dots(backend.pgm_to_raster(path, right=-1)) == {(99, 42)}


def test_raster_rejects_wrong_size(backend, tmp_path):
    path = tmp_path / "page.pgm"
    path.write_bytes(b"P5\n96 240\n255\n" + bytes(112 * 240))
    with pytest.raises(ValueError, match="112x240"):
        backend.pgm_to_raster(path)


