@needs_gs
@pytest.mark.parametrize("from_file", [False, True])
def test_prints_each_label_with_aiyin_sequence(backend, tmp_path, monkeypatch, capsys, from_file):
    device = usb.core.Device()
    usb.core.DEVICES[:] = [device]
    pdf = make_pdf(tmp_path / "label.pdf")
    if from_file:
        code = run(backend, "2", "FicheroDensity=1", str(pdf), monkeypatch=monkeypatch)
    else:
        monkeypatch.setattr("sys.stdin", io.TextIOWrapper(io.BytesIO(pdf.read_bytes())))
        code = run(backend, "2", "FicheroDensity=1", monkeypatch=monkeypatch)
    assert code == 0
    labels = 2 if from_file else 1  # From stdin, pdftopdf already made the copies.
    commands = [w for w in device.writes if len(w) < 256]
    per_label = [bytes([0x10, 0xFF, 0x10, 0x00, 1]), bytes([0x10, 0xFF, 0x84, 0x00]),
                 bytes(12), bytes([0x10, 0xFF, 0xFE, 0x01])]
    assert commands[:4] == per_label
    assert commands.count(bytes([0x1D, 0x0C])) == labels
    assert commands[-1] == bytes([0x10, 0xFF, 0xFE, 0x45])
    image = b"".join(device.writes[4:4 + 12])  # 8-byte header + 2880 bytes, 256 per write
    assert image[:8] == bytes([0x1D, 0x76, 0x30, 0, 12, 0, 240, 0])
    assert any(image[8:]), "the label must contain black dots"
    assert not device.claimed and not device.detached and device.disposed
    assert f"PAGE: {labels} 1" in capsys.readouterr().err


