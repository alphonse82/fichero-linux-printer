# --- Real CUPS filter chain ------------------------------------------------------


@needs_gs
@pytest.mark.skipif(not CUPSFILTER, reason="cupsfilter not installed")
def test_real_cups_pipeline_makes_copies(backend, tmp_path, ppd):
    source = make_pdf(tmp_path / "label.pdf")
    result = subprocess.run(
        [CUPSFILTER, "-p", str(ppd), "-e", "-m", "printer/fichero", "-i",
         "application/pdf", "-n", "2", "-o", "PageSize=14x30mm", str(source)],
        capture_output=True, check=True, timeout=30)
    processed = tmp_path / "processed.pdf"
    processed.write_bytes(result.stdout)
    rendered = tmp_path / "pages"
    rendered.mkdir()
    pages = backend.render(str(processed), rendered)
    assert len(pages) == 2 and pages[0] == pages[1] and any(pages[0])


# --- Reference: same bytes as fichero-printer's own USB print path ----------------


def test_same_usb_stream_as_fichero_printer(backend):
    cli = pytest.importorskip("fichero.cli", reason="fichero-printer not installed")
    printer = pytest.importorskip("fichero.printer")
    Image = pytest.importorskip("PIL.Image")
    raster = bytes((x * 37 + x // 12 * 11) % 256 for x in range(12 * 240))
    pixels = bytes(0 if raster[i // 8] >> (7 - i % 8) & 1 else 255 for i in range(96 * 240))

    class Recorder:
        is_usb = True

        def __init__(self):
            self.writes = []

        async def write_gatt_char(self, uuid, data, response=False):
            self.writes.append(bytes(data))

    reference = Recorder()
    with patch("asyncio.sleep", AsyncMock()):
        asyncio.run(cli.do_print(printer.PrinterClient(reference),
                                 Image.frombytes("L", (96, 240), pixels),
                                 density=1, dither=False))
    device = usb.core.Device()
    usb.core.DEVICES[:] = [device]
    ours = backend.Printer("EXAMPLE123")
    ours.label(raster, 1)
    ours.close()
    assert device.writes == reference.writes


